// Build: bundle ELK into one file, generate src/embed.generated.ts with all
// assets inlined, then compile the standalone windows-x64 binary with bun.
// Run: bun run build
// Version is injected via MMDX_VERSION (CI sets it from the git tag).

import { $ } from 'bun';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = import.meta.dir + '/..';
const read = (p: string): string => fs.readFileSync(path.join(ROOT, p), 'utf8');

// 1. ELK → single self-contained ESM bundle
const elkEntry = 'node_modules/@mermaid-js/layout-elk/dist/mermaid-layout-elk.esm.min.mjs';
const built = await Bun.build({
  entrypoints: [path.join(ROOT, elkEntry)],
  target: 'browser',
  format: 'esm',
  minify: true,
});
const elkJs = await built.outputs[0].text();
fs.mkdirSync(path.join(ROOT, 'vendor'), { recursive: true });
await Bun.write(path.join(ROOT, 'vendor/elk.bundle.mjs'), elkJs);

// 2. mermaid UMD stays as-is
fs.copyFileSync(
  path.join(ROOT, 'node_modules/mermaid/dist/mermaid.min.js'),
  path.join(ROOT, 'vendor/mermaid.min.js'),
);

// 2b. pele browser bundle (default engine)
fs.copyFileSync(
  path.join(ROOT, 'node_modules/pele/dist/pele.global.js'),
  path.join(ROOT, 'vendor/pele.global.js'),
);

// 2c. rough.js for hand-drawn themes
fs.copyFileSync(
  path.join(ROOT, 'node_modules/roughjs/bundled/rough.js'),
  path.join(ROOT, 'vendor/rough.js'),
);

// 3. fonts → base64 (sans universal; serif/kai for authored HTML pages)
const fontB64Of = (name: string): string | null => {
  const p = path.join(ROOT, 'assets/fonts', name);
  return fs.existsSync(p) ? Buffer.from(fs.readFileSync(p)).toString('base64') : null;
};
const fontB64 = fontB64Of('NotoSansSC-Subset.woff2');
const fontSerifB64 = fontB64Of('NotoSerifSC-Subset.woff2');
const fontKaiB64 = fontB64Of('LXGWWenKai-Subset.woff2');

// 4. version from tag (CI) or default
const buildVersion = process.env.MMDX_VERSION ?? null;

// 5. generated embed module
const generated =
  `// AUTO-GENERATED by scripts/build.ts — do not edit.\n` +
  `export const MERMAID_JS = ${JSON.stringify(read('vendor/mermaid.min.js'))};\n` +
  `export const ELK_JS = ${JSON.stringify(elkJs)};\n` +
  `export const PELE_JS = ${JSON.stringify(read('vendor/pele.global.js'))};\n` +
  `export const ROUGH_JS = ${JSON.stringify(read('vendor/rough.js'))};\n` +
  `export const FONT_B64 = ${JSON.stringify(fontB64)};\n` +
  `export const FONT_SERIF_B64 = ${JSON.stringify(fontSerifB64)};\n` +
  `export const FONT_KAI_B64 = ${JSON.stringify(fontKaiB64)};\n` +
  `export const BUILD_VERSION = ${JSON.stringify(buildVersion)};\n`;
fs.writeFileSync(path.join(ROOT, 'src/embed.generated.ts'), generated);

// 6. compile the standalone windows-x64 binary (svgo/browser bundles cleanly)
fs.mkdirSync(path.join(ROOT, 'dist'), { recursive: true });
await $`bun build ${path.join(ROOT, 'src/cli.ts')} --compile --target=bun-windows-x64 --outfile ${path.join(ROOT, 'dist/mmdx-windows-x64.exe')}`;

// Keep the tracked stub small; the compiled binary already carries the assets.
fs.writeFileSync(
  path.join(ROOT, 'src/embed.generated.ts'),
  '// AUTO-GENERATED by scripts/build.ts — do not edit.\n' +
  '// Committed as an empty stub; a real build replaces it with inlined assets.\n' +
  "export const MERMAID_JS = '';\n" +
  "export const ELK_JS = '';\n" +
  "export const PELE_JS = '';\n" +
  "export const ROUGH_JS = '';\n" +
  'export const FONT_B64: string | null = null;\n' +
  'export const BUILD_VERSION: string | null = null;\n',
);
console.log('built dist/mmdx-windows-x64.exe');
