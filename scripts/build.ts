// Build: vendor the Pele bundle and rough.js, generate src/embed.generated.ts
// with all assets inlined, then compile the standalone windows-x64 binary with
// bun. Run: bun run build
// Version is injected via MMDX_VERSION (CI sets it from the git tag).

import { $ } from 'bun';
import fs from 'node:fs';
import path from 'node:path';
import { BUNDLED_FONTS } from '../src/fonts.ts';

const ROOT = import.meta.dir + '/..';
const read = (p: string): string => fs.readFileSync(path.join(ROOT, p), 'utf8');

// 1. Pele browser bundle (the only engine)
fs.mkdirSync(path.join(ROOT, 'vendor'), { recursive: true });
fs.copyFileSync(
  path.join(ROOT, 'node_modules/pele/dist/pele.global.js'),
  path.join(ROOT, 'vendor/pele.global.js'),
);

// 2. rough.js for hand-drawn themes
fs.copyFileSync(
  path.join(ROOT, 'node_modules/roughjs/bundled/rough.js'),
  path.join(ROOT, 'vendor/rough.js'),
);

// 3. fonts → base64 (registry order: base sans, serif/kai, per-theme display faces, mono)
const fontFiles = BUNDLED_FONTS.flatMap((f) => f.faces.map((face) => face.file));
const fontMap: Record<string, string> = {};
for (const name of fontFiles) {
  const p = path.join(ROOT, 'assets/fonts', name);
  if (!fs.existsSync(p)) throw new Error(`bundled font missing: assets/fonts/${name}`);
  fontMap[name] = Buffer.from(fs.readFileSync(p)).toString('base64');
}

// 4. version from tag (CI) or default
const buildVersion = process.env.MMDX_VERSION ?? null;

// 5. generated embed module
const generated =
  `// AUTO-GENERATED by scripts/build.ts — do not edit.\n` +
  `export const PELE_JS = ${JSON.stringify(read('vendor/pele.global.js'))};\n` +
  `export const ROUGH_JS = ${JSON.stringify(read('vendor/rough.js'))};\n` +
  `export const FONT_FILES: Record<string, string> = ${JSON.stringify(fontMap)};\n` +
  `export const BUILD_VERSION = ${JSON.stringify(buildVersion)};\n`;
fs.writeFileSync(path.join(ROOT, 'src/embed.generated.ts'), generated);

// 6. compile the standalone windows-x64 binary (svgo/browser bundles cleanly)
fs.mkdirSync(path.join(ROOT, 'dist'), { recursive: true });
await $`bun build ${path.join(ROOT, 'src/cli.ts')} --compile --target=bun-windows-x64 --outfile ${path.join(ROOT, 'dist/mmdx-windows-x64.exe')}`;

// Keep the tracked stub small; the compiled binary already carries the assets.
fs.writeFileSync(
  path.join(ROOT, 'src/embed.generated.ts'),
  '// AUTO-GENERATED by scripts/build.ts — do not edit.\n' +
  '// Committed as an empty stub; a real build replaces it with inlined assets.\n' +
  "export const PELE_JS = '';\n" +
  "export const ROUGH_JS = '';\n" +
  'export const FONT_FILES: Record<string, string> = {};\n' +
  'export const BUILD_VERSION: string | null = null;\n',
);
console.log('built dist/mmdx-windows-x64.exe');
